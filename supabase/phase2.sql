create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  customer_name text not null,
  customer_email text,
  customer_phone text not null,
  items jsonb not null,
  total numeric not null,
  payment_status text not null default 'Belum Bayar',
  order_status text not null default 'Pesanan Baru',
  created_at timestamptz not null default now()
);

alter table public.orders enable row level security;

-- Siapa saja (customer belum login) boleh BIKIN pesanan baru,
-- tapi TIDAK BOLEH baca pesanan siapapun (demi privasi).
drop policy if exists "Anyone can create an order" on public.orders;
create policy "Anyone can create an order"
on public.orders
for insert
to anon, authenticated
with check (true);

-- Hanya admin yang boleh melihat semua pesanan.
drop policy if exists "Admins can view all orders" on public.orders;
create policy "Admins can view all orders"
on public.orders
for select
to authenticated
using ((select is_admin()));

-- Hanya admin yang boleh update status pesanan.
drop policy if exists "Admins can update orders" on public.orders;
create policy "Admins can update orders"
on public.orders
for update
to authenticated
using ((select is_admin()))
with check ((select is_admin()));

-- Hanya admin yang boleh hapus pesanan.
drop policy if exists "Admins can delete orders" on public.orders;
create policy "Admins can delete orders"
on public.orders
for delete
to authenticated
using ((select is_admin()));

-- GRANT: anon cuma boleh INSERT (tidak bisa baca balik).
-- Admin (authenticated) boleh kelola penuh, tetap dibatasi RLS.
revoke all on table public.orders from anon;
grant insert on table public.orders to anon;

revoke all on table public.orders from authenticated;
grant select, insert, update, delete on table public.orders to authenticated;

