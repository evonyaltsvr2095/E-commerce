-- Trigger: setiap ada pembelian baru -> stok bahan bertambah & harga terbaru dipakai
create or replace function public.tambah_stok_dari_pembelian()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.ingredients
  set stock_quantity = stock_quantity + new.quantity,
      cost_per_unit = new.unit_price,
      updated_at = now()
  where id = new.ingredient_id;

  return new;
end;
$$;

drop trigger if exists trg_tambah_stok_pembelian on public.ingredient_purchases;
create trigger trg_tambah_stok_pembelian
after insert on public.ingredient_purchases
for each row
execute function public.tambah_stok_dari_pembelian();

