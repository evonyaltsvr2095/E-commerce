-- ---------------------------------------------------------
-- 5. FIX: Trigger pengurangan stok otomatis saat pesanan masuk
--    (sebelumnya salah baca dari product_ingredients, sekarang
--     pakai recipes + recipe_items + conversion_factor)
-- ---------------------------------------------------------
create or replace function public.kurangi_stok_bahan()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
declare
  item jsonb;
  v_product_id bigint;
  v_qty numeric;
begin
  for item in select * from jsonb_array_elements(new.items)
  loop
    v_product_id := (item->>'product_id')::bigint;
    v_qty := (item->>'quantity')::numeric;

    if v_product_id is not null and v_qty is not null then
      update public.ingredients ing
      set stock_quantity = ing.stock_quantity - (
            (ri.quantity_used / nullif(ing.conversion_factor, 0)) * v_qty
          ),
          updated_at = now()
      from public.recipe_items ri
      join public.recipes r on r.id = ri.recipe_id
      where ri.ingredient_id = ing.id
        and r.product_id = v_product_id;
    end if;
  end loop;

  return new;
end;
$$;

drop trigger if exists trg_kurangi_stok on public.orders;
create trigger trg_kurangi_stok
after insert on public.orders
for each row
execute function public.kurangi_stok_bahan();

