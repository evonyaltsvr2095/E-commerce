-- ---------------------------------------------------------
-- 1. INGREDIENTS (Bahan Baku)
-- ---------------------------------------------------------
create table if not exists public.ingredients (
  id bigint generated by default as identity primary key,
  name text not null,
  unit text not null,                    -- satuan besar/stok, misal: kg, L, pcs
  recipe_unit text not null default 'gram', -- satuan resep, misal: gram, ml, pcs
  conversion_factor numeric not null default 1, -- 1 unit besar = berapa recipe_unit
  stock_quantity numeric not null default 0,
  cost_per_unit numeric not null default 0, -- harga per satuan besar (unit)
  low_stock_threshold numeric not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- Jaga-jaga kalau tabel sudah ada dari versi lama tanpa kolom ini:
alter table public.ingredients add column if not exists recipe_unit text not null default 'gram';
alter table public.ingredients add column if not exists conversion_factor numeric not null default 1;
alter table public.ingredients add column if not exists low_stock_threshold numeric not null default 0;
alter table public.ingredients add column if not exists updated_at timestamptz not null default now();

alter table public.ingredients enable row level security;

drop policy if exists "Admins can manage ingredients" on public.ingredients;
create policy "Admins can manage ingredients"
on public.ingredients
for all
to authenticated
using ((select is_admin()))
with check ((select is_admin()));

revoke all on table public.ingredients from anon;
revoke all on table public.ingredients from authenticated;
grant select, insert, update, delete on table public.ingredients to authenticated;

